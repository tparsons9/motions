export function additionalDefinitions(core: string): string {
    let result = '\nvim.fn = {}\n';
    for (const namespace of ['api', 'fn'] as const)
        for (const status of ['real', 'stub'] as const) {
            for (const name of surface[namespace][status]) {
                if (core.includes(`function vim.${namespace}.${name}(`))
                    continue;
                result +=
                    status === 'stub'
                        ? '\n---@deprecated Unsupported in bundled Motions; compatibility stub only.\n'
                        : '\n---Bundled Motions implementation; see its Lua API reference for limitations.\n';
                result += `---@param ... any\n---@return any\nfunction vim.${namespace}.${name}(...) end\n`;
            }
        }
    return result;
}
